// Writers for the token set: JSON (everything), CSS custom properties (Material Web's md-sys-* names), a Dart
// theme for package:flutter/material.dart, and a readable report.
import { colorRoles, kebab, LEGACY_ROLES, TYPE_ROLES } from './google.mjs';

const rem = (px) => `${Number((px / 16).toFixed(5))}rem`;
const header = (t, comment) => comment(`Generated by the material-3 skill (scripts/tokens.mjs) from "${t.meta.name}" on ${t.meta.generated}. Regenerate it; never edit by hand.`);

// --- CSS ---------------------------------------------------------------------------------------------------

function colorBlock(colors) {
  return colorRoles().map((r) => `  --md-sys-color-${kebab(r)}: ${colors[r]};`).join('\n');
}

export function toCss(t) {
  const out = [header(t, (s) => `/* ${s} */`)];
  const { light, dark } = t.color;
  if (light) out.push(`:root, [data-theme="light"] {\n  color-scheme: light;\n${colorBlock(light.colors)}\n}`);
  if (dark && light) {
    out.push(`[data-theme="dark"] {\n  color-scheme: dark;\n${colorBlock(dark.colors)}\n}`);
    out.push(`@media (prefers-color-scheme: dark) {\n  :root:not([data-theme="light"]) {\n    color-scheme: dark;\n${colorBlock(dark.colors).replace(/^/gm, '  ')}\n  }\n}`);
  } else if (dark) {
    out.push(`:root, [data-theme="dark"] {\n  color-scheme: dark;\n${colorBlock(dark.colors)}\n}`);
  }
  const v = [];
  v.push(`  --md-ref-typeface-brand: ${t.typeface.brandStack};`);
  v.push(`  --md-ref-typeface-plain: ${t.typeface.plainStack};`);
  for (const [w, n] of Object.entries(t.typeface.weights)) v.push(`  --md-ref-typeface-weight-${w}: ${n};`);
  const type = (prefix, role, s) => {
    v.push(`  ${prefix}-font: var(--md-ref-typeface-${s.face});`);
    v.push(`  ${prefix}-size: ${rem(s.size)};`);
    v.push(`  ${prefix}-line-height: ${rem(s.lineHeight)};`);
    v.push(`  ${prefix}-weight: ${s.weight};`);
    v.push(`  ${prefix}-tracking: ${rem(s.tracking)};`);
  };
  for (const role of TYPE_ROLES) type(`--md-sys-typescale-${role}`, role, t.typescale.baseline[role]);
  for (const role of TYPE_ROLES) type(`--md-sys-typescale-emphasized-${role}`, role, t.typescale.emphasized[role]);
  for (const [step, val] of Object.entries(t.shape.scale)) v.push(`  --md-sys-shape-corner-${step}: ${val === 'full' ? '9999px' : `${val}px`};`);
  for (const [lvl, dp] of Object.entries(t.elevation)) v.push(`  --md-sys-elevation-${lvl}: ${dp};`);
  for (const [s, o] of Object.entries(t.state)) v.push(`  --md-sys-state-${s}-state-layer-opacity: ${o};`);
  v.push(`  --md-sys-state-focus-indicator-thickness: ${t.focus.thickness}px;`);
  v.push(`  --md-sys-state-focus-indicator-outer-offset: ${t.focus.outerOffset}px;`);
  v.push(`  --md-sys-state-focus-indicator-inner-offset: ${t.focus.innerOffset}px;`);
  for (const [e, c] of Object.entries(t.motion.easing)) v.push(`  --md-sys-motion-easing-${e}: ${c};`);
  for (const [d, ms] of Object.entries(t.motion.duration)) v.push(`  --md-sys-motion-duration-${d}: ${ms}ms;`);
  for (const [scheme, set] of Object.entries(t.motion.springs)) {
    for (const [k, s] of Object.entries(set)) {
      v.push(`  --md-sys-motion-${scheme}-spring-${k}: ${s.css.easing};`);
      v.push(`  --md-sys-motion-${scheme}-spring-${k}-duration: ${s.css.duration}ms;`);
    }
  }
  // The project's chosen scheme under scheme-free names, so components need not know which one it is.
  for (const k of Object.keys(t.motion.springs[t.motion.scheme])) {
    v.push(`  --md-sys-motion-spring-${k}: var(--md-sys-motion-${t.motion.scheme}-spring-${k});`);
    v.push(`  --md-sys-motion-spring-${k}-duration: var(--md-sys-motion-${t.motion.scheme}-spring-${k}-duration);`);
  }
  out.push(`:root {\n${v.join('\n')}\n}`);
  return `${out.join('\n\n')}\n`;
}

// --- Dart --------------------------------------------------------------------------------------------------

const dartColor = (hex) => {
  const h = hex.replace('#', '').toUpperCase();
  const a = h.length === 8 ? h.slice(6, 8) : 'FF';
  return `Color(0x${a}${h.slice(0, 6)})`;
};
const DART_NAME = { inverseOnSurface: 'onInverseSurface' };
const dartIdent = (s) => s.replace(/-([a-z])/g, (_, c) => c.toUpperCase());

function dartScheme(name, brightness, colors) {
  const lines = colorRoles().filter((r) => !LEGACY_ROLES.includes(r))
    .map((r) => `    ${DART_NAME[r] ?? r}: ${dartColor(colors[r])},`);
  return `  static const ColorScheme ${name} = ColorScheme(\n    brightness: Brightness.${brightness},\n${lines.join('\n')}\n  );`;
}

// A Dart single-quoted string literal: backslashes, quotes, dollar signs and line breaks escaped.
const dartString = (s) => `'${String(s).replace(/[\\'$]/g, (c) => `\\${c}`).replace(/\n/g, '\\n').replace(/\r/g, '\\r')}'`;

function dartTextStyle(s, faces, variable) {
  const family = s.face === 'brand' ? faces.brand : faces.plain;
  // Flutter has FontWeight.w100 to w900 only: an in-between weight (450) takes the nearest one, and its exact value
  // travels on the wght axis. A variable font always needs that axis: FontWeight alone picks a static instance.
  const nearest = Math.min(900, Math.max(100, Math.round(s.weight / 100) * 100));
  const axis = variable || nearest !== s.weight ? `, fontVariations: [FontVariation('wght', ${s.weight})]` : '';
  return `TextStyle(fontFamily: ${dartString(family)}, fontSize: ${s.size}, height: ${Number((s.lineHeight / s.size).toFixed(4))}, letterSpacing: ${s.tracking}, fontWeight: FontWeight.w${nearest}${axis})`;
}

export function toDart(t) {
  const faces = t.typeface;
  const variable = t.typescale.variable;
  // material.dart already exports SpringDescription; importing physics.dart too fails `flutter analyze` (unnecessary_import).
  const parts = [header(t, (s) => `// ${s}`), '', "import 'package:flutter/material.dart';", ''];
  parts.push('/// Material 3 tokens for this project (Flutter 3.35 or later). Use [M3Tokens.theme] for a [ThemeData].');
  parts.push('abstract final class M3Tokens {');
  if (t.color.light) parts.push(dartScheme('lightScheme', 'light', t.color.light.colors), '');
  if (t.color.dark) parts.push(dartScheme('darkScheme', 'dark', t.color.dark.colors), '');
  parts.push('  static const TextTheme textTheme = TextTheme(');
  for (const role of TYPE_ROLES) parts.push(`    ${dartIdent(role)}: ${dartTextStyle(t.typescale.baseline[role], faces, variable)},`);
  parts.push('  );', '');
  parts.push('  /// M3 Expressive emphasized styles (Material Web latest tokens; Flutter has no emphasized TextTheme slots).');
  for (const role of TYPE_ROLES) parts.push(`  static const TextStyle ${dartIdent(`emphasized-${role}`)} = ${dartTextStyle(t.typescale.emphasized[role], faces, variable)};`);
  parts.push('');
  for (const [step, val] of Object.entries(t.shape.scale)) {
    parts.push(`  static const double ${dartIdent(`corner-${step}`)} = ${val === 'full' ? 'double.infinity' : `${val}`};`);
  }
  parts.push('');
  for (const [scheme, set] of Object.entries(t.motion.springs)) {
    for (const [k, s] of Object.entries(set)) {
      parts.push(`  static final SpringDescription ${dartIdent(`${scheme}-${k}`)} = SpringDescription.withDampingRatio(mass: 1, stiffness: ${s.stiffness}, ratio: ${s.damping});`);
    }
  }
  parts.push('');
  const corner = (step) => (t.shape.scale[step] === 'full' ? 'const StadiumBorder()' : `RoundedRectangleBorder(borderRadius: BorderRadius.circular(${t.shape.scale[step]}))`);
  parts.push('  static ThemeData theme(ColorScheme scheme) {');
  parts.push('    return ThemeData(');
  parts.push('      useMaterial3: true,');
  parts.push('      colorScheme: scheme,');
  parts.push('      textTheme: textTheme.apply(bodyColor: scheme.onSurface, displayColor: scheme.onSurface),');
  parts.push('      // M3 retired the elevation tint: a scrolled app bar turns surfaceContainer, untinted (Flutter still tints it).');
  parts.push('      appBarTheme: const AppBarThemeData(surfaceTintColor: Colors.transparent),');
  parts.push("      // Flutter draws Material 2 tooltips (90% white in dark themes); M3's plain tooltip is inverse-surface, body-small.");
  parts.push(`      tooltipTheme: TooltipThemeData(decoration: BoxDecoration(color: scheme.inverseSurface, borderRadius: BorderRadius.circular(${t.shape.scale['extra-small']})), textStyle: textTheme.bodySmall!.copyWith(color: scheme.onInverseSurface)),`);
  if (t.shape.overridden) {
    // Only when the brand changes M3's corners: carry them into the components that use each step.
    const btn = `ButtonStyle(shape: WidgetStatePropertyAll(${corner('full')}))`;
    parts.push(`      filledButtonTheme: FilledButtonThemeData(style: ${btn}),`);
    parts.push(`      outlinedButtonTheme: OutlinedButtonThemeData(style: ${btn}),`);
    parts.push(`      textButtonTheme: TextButtonThemeData(style: ${btn}),`);
    parts.push(`      elevatedButtonTheme: ElevatedButtonThemeData(style: ${btn}),`);
    parts.push(`      cardTheme: CardThemeData(shape: ${corner('medium')}),`);
    parts.push(`      dialogTheme: DialogThemeData(shape: ${corner('extra-large')}),`);
    parts.push(`      floatingActionButtonTheme: FloatingActionButtonThemeData(shape: ${corner('large')}),`);
    parts.push(`      inputDecorationTheme: InputDecorationTheme(border: OutlineInputBorder(borderRadius: BorderRadius.circular(${t.shape.scale['extra-small']}))),`);
    parts.push(`      chipTheme: ChipThemeData(shape: ${corner('small')}),`);
    parts.push(`      snackBarTheme: SnackBarThemeData(shape: ${corner('extra-small')}),`);
    parts.push(`      bottomSheetTheme: BottomSheetThemeData(shape: RoundedRectangleBorder(borderRadius: BorderRadius.vertical(top: Radius.circular(${t.shape.scale['extra-large']})))),`);
  }
  parts.push('    );');
  parts.push('  }');
  parts.push('}');
  return `${parts.join('\n')}\n`;
}

// --- report ------------------------------------------------------------------------------------------------

export function toReport(t) {
  const L = [`# Material 3 tokens: ${t.meta.name}`, '', `Generated ${t.meta.generated} by \`scripts/tokens.mjs\`.`, ''];
  L.push(`- **Source color:** ${t.meta.source}; **variant:** ${t.meta.variant}; **contrast level:** ${t.meta.contrast}; **color spec:** ${t.meta.spec}`);
  L.push(`- **Motion scheme:** ${t.motion.scheme}; **typefaces:** brand ${t.typeface.brand}, plain ${t.typeface.plain}`);
  L.push(`- **Google's sources:** ${Object.entries(t.meta.google).map(([k, v]) => `${k} ${v.commit.slice(0, 10)} (${v.commit_date.slice(0, 10)})`).join('; ')}`);
  if (t.shape.overridden) L.push(`- **Departures from M3's corner scale (the brand's):** ${t.shape.overrides.map(([k, v]) => `${k} ${v}px`).join(', ')}`);
  if (t.typescale.overrides.length) L.push(`- **Departures from M3's type scale (the brand's):** ${t.typescale.overrides.map(([k, v]) => `${k} ${Object.entries(v).map(([p, n]) => `${p} ${n}`).join(' ')}`).join('; ')}`);
  if (t.typescale.variable) L.push('- **Variable font:** emphasized weights from the wght axis (600 for titles and labels, where static fonts use 700).');
  for (const [mode, m] of Object.entries(t.color)) {
    if (!m) continue;
    const count = (o) => Object.values(m.origin).filter((x) => x === o).length;
    L.push('', `## ${mode}`, '', `${count('locked')} locked, ${count('generated')} generated, ${count('adjusted')} adjusted of ${colorRoles().length} roles.`, '');
    if (m.notes.length) L.push(...m.notes.map((n) => `- ${n}`), '');
    const fails = m.contrast.filter((c) => !c.pass);
    if (fails.length) {
      L.push('**Failing pairs:**', '');
      for (const f of fails) {
        const s = f.suggestion ? ` Nearest passing ${f.fg}: ${f.suggestion.hex} (tone ${f.suggestion.tone}), a departure for the owner to decide.` : '';
        L.push(`- ${f.fg} on ${f.bg}: ${f.ratio}:1, needs ${f.min}:1${f.brandLocked ? ' — brand-locked' : ''}.${s}`);
      }
      L.push('');
    } else {
      L.push(`All ${m.contrast.length} required pairs pass (text 4.5:1, UI 3:1). outlineVariant on surface: ${m.decorative.ratio}:1, decorative only.`, '');
    }
    L.push('| Role | Color | Origin |', '|---|---|---|');
    for (const r of colorRoles()) L.push(`| ${r} | ${m.colors[r]} | ${m.origin[r]} |`);
  }
  return `${L.join('\n')}\n`;
}
